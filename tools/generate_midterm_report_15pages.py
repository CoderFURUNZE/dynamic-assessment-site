def set_font(run, size=11, bold=False):
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.bold = bold


def set_para(paragraph, first_line=True, spacing_after=6):
    fmt = paragraph.paragraph_format
    fmt.line_spacing = 1.5
    fmt.space_after = Pt(spacing_after)
    if first_line:
        fmt.first_line_indent = Pt(22)


def clear_cell(cell):
    tc = cell._tc
    for child in list(tc):
        if child.tag.endswith("tcPr"):
            continue
        tc.remove(child)
    tc.append(OxmlElement("w:p"))


def add_p(cell, text="", size=12, bold=False, first_line=True, spacing_after=6):
    p = cell.add_paragraph()
    set_para(p, first_line=first_line, spacing_after=spacing_after)
    r = p.add_run(text)
    set_font(r, size=size, bold=bold)
    return p


def add_heading(cell, text, level=2):
    size = 15 if level == 1 else 13
    p = cell.add_paragraph()
    set_para(p, first_line=False, spacing_after=8)
    r = p.add_run(text)
    set_font(r, size=size, bold=True)


def add_break(cell):
    p = cell.add_paragraph()
    r = p.add_run()
    r.add_break(WD_BREAK.PAGE)


